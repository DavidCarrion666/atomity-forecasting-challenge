"""Time-aware validation utilities for the cloud workload forecasting challenge.

Design principles
-----------------
- **No shuffling**: all splits respect chronological order.
- **Expanding window**: each fold adds one more observation to the training set.
- **No leakage**: validation windows never overlap with the final 24-step
  holdout.

Recommended usage for this challenge
--------------------------------------
With 110 training observations and a 24-step forecast horizon:

    from cwfc.validation import expanding_window_splits

    splits = expanding_window_splits(n_total=110, horizon=24, min_train=48, step=1)
    # → 39 folds:
    #   Fold 0:  train on obs 0..47 (n=48)  → validate on obs 48..71 (horizon=24)
    #   ...
    #   Fold 38: train on obs 0..85 (n=86)  → validate on obs 86..109 (horizon=24)

This yields 39 validation folds strictly confined to the 110 training observations
(indices 0..109). The 24 holdout observations (indices 110..133) are never touched.

Overlapping validation windows and non-independence
---------------------------------------------------
Because windows advance by step=1 with horizon=24:
- The 39 folds generate 39 × 24 = 936 prediction-actual pairs in total.
- However, these pairs cover only 62 distinct timestamps (indices 48 to 109).
- Observations in the middle (indices 71 to 86) appear in up to 24 distinct
  validation windows, each evaluated at a different forecast horizon step
  (from h=24 down to h=1).
- Consequently, the 936 evaluation pairs are NOT independent observations.
  Errors across successive folds for the same observation, and errors within
  a fold across the 24-step horizon, exhibit strong serial correlation.
"""

from __future__ import annotations

from dataclasses import dataclass

import numpy as np
import pandas as pd


# ── Dataclasses ──────────────────────────────────────────────────────────────

@dataclass(frozen=True)
class IndexSplit:
    """Integer-index based split.

    Attributes
    ----------
    train_end:
        Exclusive upper bound of the training slice (i.e., train = [:train_end]).
    val_start:
        Start of the validation slice (inclusive).
    val_end:
        End of the validation slice (exclusive).
    """
    train_end: int
    val_start: int
    val_end: int

    @property
    def n_train(self) -> int:
        return self.train_end

    @property
    def n_val(self) -> int:
        return self.val_end - self.val_start


@dataclass(frozen=True)
class TimeSplit:
    """Timestamp-based split (backwards-compatible with the original validation.py)."""
    train_end: pd.Timestamp
    validation_start: pd.Timestamp
    validation_end: pd.Timestamp


# ── Core split generators ─────────────────────────────────────────────────────

def expanding_window_splits(
    n_total: int,
    horizon: int,
    min_train: int = 48,
    step: int = 1,
) -> list[IndexSplit]:
    """Generate expanding-window (growing train) splits on integer indices.

    Parameters
    ----------
    n_total:
        Total number of training observations (NOT including holdout).
        For this challenge: 110.
    horizon:
        Forecast horizon in steps.  For this challenge: 24.
    min_train:
        Minimum number of observations required before the first validation
        window.  Default 48 = 4 hours at 5-min cadence.
    step:
        Number of observations to advance the origin between folds.
        step=1 gives a full rolling-origin evaluation (most thorough).
        step=horizon gives non-overlapping windows.

    Returns
    -------
    list[IndexSplit]
        Each split: train = series[:train_end], val = series[val_start:val_end].

    Notes
    -----
    All splits stay within ``n_total``; the holdout (observations 110–133)
    is never touched.
    """
    if min_train < 1:
        raise ValueError("min_train must be at least 1")
    if horizon < 1:
        raise ValueError("horizon must be at least 1")
    if step < 1:
        raise ValueError("step must be at least 1")

    splits: list[IndexSplit] = []
    train_end = min_train  # exclusive upper bound of train slice

    while train_end + horizon <= n_total:
        splits.append(
            IndexSplit(
                train_end=train_end,
                val_start=train_end,
                val_end=train_end + horizon,
            )
        )
        train_end += step

    return splits


def get_validation_overlap(splits: list[IndexSplit]) -> pd.DataFrame:
    """Analyze which observations appear in multiple validation windows.

    Parameters
    ----------
    splits:
        List of :class:`IndexSplit` generated by :func:`expanding_window_splits`.

    Returns
    -------
    pd.DataFrame
        DataFrame with columns:
        - ``observation_index``: integer index of the evaluated observation.
        - ``count``: number of validation windows that include this observation.
        - ``first_fold``: index of the first fold evaluating this observation.
        - ``last_fold``: index of the last fold evaluating this observation.
        - ``min_horizon``: lowest forecast horizon step (1-indexed) for this obs.
        - ``max_horizon``: highest forecast horizon step (1-indexed) for this obs.

    Notes
    -----
    In rolling-origin evaluation (step=1), validation windows overlap heavily:
    each observation enters validation at horizon=H and remains in subsequent
    folds until horizon=1.
    """
    from collections import defaultdict

    obs_folds: dict[int, list[tuple[int, int]]] = defaultdict(list)
    for fold_idx, sp in enumerate(splits):
        for h_step, obs_idx in enumerate(range(sp.val_start, sp.val_end), start=1):
            obs_folds[obs_idx].append((fold_idx, h_step))

    records = []
    for obs_idx in sorted(obs_folds.keys()):
        entries = obs_folds[obs_idx]
        folds = [f for f, _ in entries]
        horizons = [h for _, h in entries]
        records.append(
            {
                "observation_index": obs_idx,
                "count": len(entries),
                "first_fold": min(folds),
                "last_fold": max(folds),
                "min_horizon": min(horizons),
                "max_horizon": max(horizons),
            }
        )
    return pd.DataFrame(records)


def rolling_origin_splits(
    frame: pd.DataFrame,
    timestamp_col: str = "timestamp",
    horizon: int = 288,
    min_train_size: int = 7 * 24 * 12,
    step: int | None = None,
) -> list[TimeSplit]:
    """Return expanding-window splits for evenly sampled time series.

    This is the original timestamp-based variant kept for backwards
    compatibility.  ``horizon=288`` is one day at 5-minute cadence.
    """
    if horizon <= 0 or min_train_size <= 0:
        raise ValueError("horizon and min_train_size must be positive")
    ts = pd.to_datetime(frame[timestamp_col], utc=True)
    if not ts.is_monotonic_increasing:
        raise ValueError("timestamps must be sorted")
    n = len(frame)
    step = horizon if step is None else step
    out: list[TimeSplit] = []
    train_end_idx = min_train_size
    while train_end_idx + horizon <= n:
        train_end = ts.iloc[train_end_idx - 1]
        val_start = ts.iloc[train_end_idx]
        val_end = ts.iloc[train_end_idx + horizon - 1]
        out.append(TimeSplit(train_end, val_start, val_end))
        train_end_idx += step
    return out


# ── Convenience: apply a forecaster over all splits ──────────────────────────

def cross_validate(
    series: np.ndarray,
    forecaster,
    splits: list[IndexSplit],
) -> list[dict]:
    """Evaluate ``forecaster`` over each split in ``splits``.

    Parameters
    ----------
    series:
        Full 1-D target array (length = ``n_total``).
    forecaster:
        Callable with signature ``(train: np.ndarray, horizon: int) -> np.ndarray``.
    splits:
        Output of :func:`expanding_window_splits`.

    Returns
    -------
    list[dict]
        One dict per fold with keys:
        ``fold``, ``n_train``, ``horizon``, ``y_true``, ``y_pred``.
    """
    results = []
    for i, sp in enumerate(splits):
        train = series[: sp.train_end]
        y_true = series[sp.val_start : sp.val_end]
        horizon = sp.n_val
        y_pred = forecaster(train, horizon)
        results.append(
            {
                "fold": i,
                "n_train": sp.n_train,
                "horizon": horizon,
                "y_true": y_true,
                "y_pred": y_pred,
            }
        )
    return results
